const cache = new Map<Art, string>();

export function shopArt(id: Art): string {
  let svg = cache.get(id);
  if (!svg) {
    let rects = '';
    ART[id].forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const fill = PAL[row[x]];
        if (fill) rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`;
      }
    });
    svg = `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
    cache.set(id, svg);
  }
  return svg;
}
